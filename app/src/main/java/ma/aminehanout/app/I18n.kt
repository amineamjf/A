private fun li(): Int = when (lang) { "fr" -> 1; "dr" -> 2; else -> 0 }

fun tr(k: String, vararg a: Any): String {
    val arr = S[k]
    val s = arr?.getOrNull(li()) ?: arr?.get(0) ?: k
    return if (a.isEmpty()) s else String.format(Locale.US, s, *a)
}

fun digits(s: String): String {
    if (!eastDigits) return s
    val sb = StringBuilder()
    for (ch in s) sb.append(when (ch) { in '0'..'9' -> '٠' + (ch - '0'); '.' -> '٫'; ',' -> '٬'; else -> ch })
    return sb.toString()
}

